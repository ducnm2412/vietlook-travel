export type DictKey = keyof (typeof dict)["en"];

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

// Ngôn ngữ nằm trong đường dẫn (/en, /zh – xem proxy.ts); đổi ngôn ngữ = mở cùng trang với tiền tố còn lại
export function LangProvider({ children, initial = "en" }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(initial);

  const setLang = (l: Lang) => {
    if (l === lang) return;
    setLangState(l);
    document.cookie = `lang=${l}; path=/; max-age=31536000`;
    const { pathname, search, hash } = window.location;
    window.location.assign(`/${l}${pathname.replace(/^\/(en|zh)(?=\/|$)/, "")}${search}${hash}`);
  };

  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useLang() {
  const { lang, setLang } = useContext(LangContext);
  const t = (k: DictKey) => dict[lang][k] ?? dict.en[k];
  return { lang, setLang, t };
}

/** Chuỗi giao diện dùng được trong server component: <T k="nav.tours" /> */
export function T({ k }: { k: DictKey }) {
  return <>{useLang().t(k)}</>;
}

/** Nội dung có 2 bản EN / ZH (tên tour, điểm đến...) */
export function L({ en, zh }: { en: string; zh?: string }) {
  const { lang } = useLang();
  return <>{lang === "zh" && zh ? zh : en}</>;
}

export function LHtml({ en, zh, className }: { en: string; zh?: string | null; className?: string }) {
  const { lang } = useLang();
  return <div className={className} dangerouslySetInnerHTML={{ __html: lang === "zh" && zh ? zh : en }} />;
}
